    /// Return the input schema pretty-printed as a JSON string.
    ///
    /// # Example
    ///
    /// ```rust
    /// use tokitai_core::ToolDefinition;
    ///
    /// let tool = ToolDefinition::new(
    ///     "add",
    ///     "Add two numbers",
