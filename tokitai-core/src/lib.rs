/// # Runtime-Agnostic Async Executor
///
/// Bridge for the `#[tool]` macro's sync-from-async path that decouples
/// Tokitai from Tokio. The macro's sync wrapper delegates to a registered
/// [`AsyncExecutor`]; install one with [`set_async_executor`] to use
/// `async-std`, `smol`, `embassy`, or any custom executor.
///
/// ## Default behaviour
///
/// 1. Custom executor registered via [`set_async_executor`] -> use it.
/// 2. Otherwise, if inside a Tokio runtime, use the active
///    `Handle::block_on` (preserves backward compatibility).
/// 3. Otherwise, return a [`ToolError`] with a descriptive English message.
///
/// ## No-`std` fallback
///
/// When the `serde` feature is disabled the crate is `no_std` and no
/// executor is reachable; [`block_on_async`] always returns a
/// `ToolError::InternalError` so the macro can still type-check.
///
/// [`block_on_async`]: crate::block_on_async
///
/// This trait is **object-safe** so the user-registered executor can be
/// stored as `&'static dyn AsyncExecutor`. The type-erased
/// [`AsyncExecutor::block_on_dyn`] takes a boxed future and returns a boxed
/// output; typed convenience is provided by [`AsyncExecutorExt`].
///
/// ## T-003 per-call override seam
///
/// Implementations may override [`AsyncExecutor::block_on_for`] to return
/// `Some(...)` when an ambient executor (per-`call_tool`, per-thread, etc.)
/// is reachable. The `#[tool]` macro's sync-from-async wrapper probes
/// `block_on_for` first, then the global slot set via
/// [`set_async_executor`], then the active Tokio runtime. This is how
/// `async-std` / `smol` / `embassy` users supply an executor without
/// mutating global state.
pub trait AsyncExecutor: Send + Sync {
    /// Object-safe entry point: drive a boxed future to completion on the
    /// current thread and return its output as a boxed `Any`. Most users
    /// implement [`AsyncExecutorExt::block_on`] and let the blanket impl
    /// derive this; override it directly only for full control.
    ///
    /// # Example
    ///
    /// ```rust,ignore
    /// use tokitai_core::AsyncExecutor;
    /// use core::future::Future;
    /// use core::pin::Pin;
    /// use core::any::Any;
    ///
    /// struct ThreadPoolExecutor;
    /// impl AsyncExecutor for ThreadPoolExecutor {
    ///     fn block_on_dyn(
    ///         &self,
    ///         future: Pin<Box<dyn Future<Output = ()> + Send>>,
    ///     ) -> Box<dyn Any + Send> {
    ///         // ... drive the future to completion ...
    ///         # Box::new(())
    ///     }
    /// }
    /// ```
    fn block_on_dyn(
        &self,
        future: core::pin::Pin<Box<dyn core::future::Future<Output = ()> + Send>>,
    ) -> Box<dyn core::any::Any + Send>;

    /// Per-call override seam (T-003). The `#[tool]` macro's sync
    /// wrapper probes this *before* the global slot, so users who do not
    /// want a process-wide side effect can supply an executor locally.
    ///
    /// Return `None` to indicate "no ambient executor; fall through to
    /// the global slot / Tokio probe." The default implementation always
    /// returns `None`; runtime-aware executors (async-std, smol, embassy)
    /// override it to return `Some(...)` when their runtime is reachable
    /// on the current thread.
    ///
    /// # Example
    ///
    /// ```rust,ignore
    /// use tokitai_core::AsyncExecutor;
    ///
    /// struct AsyncStdExecutor;
    /// impl AsyncExecutor for AsyncStdExecutor {
    ///     fn block_on_dyn(
    ///         &self,
    ///         future: core::pin::Pin<
    ///             Box<dyn core::future::Future<Output = ()> + Send>,
    ///         >,
    ///     ) -> Box<dyn core::any::Any + Send> {
    ///         // ... drive the future ...
    ///         # Box::new(())
    ///     }
    ///
    ///     fn block_on_for(
    ///         &self,
    ///     ) -> Option<&'static dyn AsyncExecutor> {
    ///         // async-std sets a thread-local handle; return `Some(self)`
    ///         // when one is reachable on this thread.
    ///         None
    ///     }
    /// }
    /// ```
    fn block_on_for(&self) -> Option<&'static dyn AsyncExecutor> {
        None
    }
}

/// Typed convenience wrapper around [`AsyncExecutor::block_on_dyn`].
/// Implemented for every `T: AsyncExecutor`; re-introduces the natural
/// `block_on<F: Future>(&self, F) -> F::Output` signature on top of the
/// type-erased entry point.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::{AsyncExecutor, AsyncExecutorExt};
///
/// fn drive<E: AsyncExecutor>(exec: &E) -> String {
///     exec.block_on(async { String::from("typed output") })
/// }
/// ```
pub trait AsyncExecutorExt: AsyncExecutor {
    /// Drive a future to completion and return its output.
    ///
    /// The future must be `Send + 'static` (so it can cross the type-erasure
    /// boundary) and its output must be `Send + 'static` (so it can be
    /// downcast on the call site).
    ///
    /// # Example
    ///
    /// ```rust,ignore
    /// use tokitai_core::{AsyncExecutor, AsyncExecutorExt};
    ///
    /// fn run<E: AsyncExecutor>(exec: &E) -> i32 {
    ///     exec.block_on(async { 21 + 21 })
    /// }
    /// ```
    ///
    /// # Panics
    ///
    /// Panics if the internal output slot mutex is poisoned or if the
    /// underlying [`AsyncExecutor::block_on_dyn`] returns without driving the
    /// future to completion.
    fn block_on<F>(&self, future: F) -> F::Output
    where
        F: core::future::Future + Send + 'static,
        F::Output: Send + 'static,
    {
        use core::any::Any;
        use core::sync::atomic::{AtomicBool, Ordering};
        use std::sync::{Arc, Mutex};

        let slot: Arc<Mutex<Option<F::Output>>> = Arc::new(Mutex::new(None));
        let ran: Arc<AtomicBool> = Arc::new(AtomicBool::new(false));
        let slot_inner = slot.clone();
        let ran_inner = ran.clone();

        let wrapped = async move {
            let output = future.await;
            *slot_inner
                .lock()
                .expect("AsyncExecutor output slot poisoned") = Some(output);
            ran_inner.store(true, Ordering::Release);
        };

        let _: Box<dyn Any + Send> = self.block_on_dyn(Box::pin(wrapped));

        assert!(
            ran.load(Ordering::Acquire),
            "AsyncExecutor did not drive the future to completion"
        );

        let mut guard = slot.lock().expect("AsyncExecutor output slot poisoned");
        guard
            .take()
            .expect("future reported complete but produced no output")
    }
}

impl<T: AsyncExecutor + ?Sized> AsyncExecutorExt for T {}

/// Process-wide slot that holds the user-registered [`AsyncExecutor`].
/// A `OnceLock<Box<dyn AsyncExecutor>>` is the portable, leak-free
/// storage: the box is leaked into the static slot, so the resulting
/// reference is `&'static`.
static ASYNC_EXECUTOR: std::sync::OnceLock<Box<dyn AsyncExecutor>> = std::sync::OnceLock::new();

/// Install a global [`AsyncExecutor`] used by every `#[tool]`-generated sync
/// wrapper. Call once at program startup, before any sync `call_tool` is
/// invoked on an `async` tool. The box is leaked: the executor lives for the
/// lifetime of the program. The first call wins; subsequent calls are
/// silently ignored (best-effort registration).
///
/// # Global fallback role (T-003)
///
/// `set_async_executor` is the **process-wide fallback** used by the
/// `#[tool]` macro. The sync-from-async wrapper resolves an executor in
/// this order:
///
/// 1. [`block_on_for_executor`] — per-call / per-thread override probe
///    (T-003). Lets users wire async-std / smol / embassy without mutating
///    global state.
/// 2. The executor registered via [`set_async_executor`] (this function).
///    This is the slot `async-std` / `smol` / `embassy` users populate
///    when they want a single, program-wide bridge.
/// 3. The active Tokio runtime, when one is reachable on the current
///    thread.
/// 4. Otherwise, [`block_on_async`] returns a [`ToolError`] with the
///    canonical English message.
///
/// Use case: an `async-std` user can call this once at startup with an
/// `async_std::task::Executor` wrapper. The macro then resolves the
/// wrapper on every sync `call_tool` without the user touching the
/// macro.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::{set_async_executor, AsyncExecutor, AsyncExecutorExt};
/// use core::future::Future;
/// use core::pin::Pin;
///
/// struct BlockingExecutor;
/// impl AsyncExecutor for BlockingExecutor {
///     fn block_on_dyn(
///         &self,
///         future: Pin<Box<dyn Future<Output = ()> + Send>>,
///     ) -> Box<dyn core::any::Any + Send> {
///         Box::new(futures::executor::block_on(future))
///     }
/// }
///
/// set_async_executor(Box::new(BlockingExecutor));
/// ```
pub fn set_async_executor<E: AsyncExecutor + 'static>(executor: Box<E>) {
    let trait_obj: Box<dyn AsyncExecutor> = executor;
    // `_ =` to ignore the `AlreadyInitialized` error; the registration
    // is best-effort. The first executor wins.
    let _ = ASYNC_EXECUTOR.set(trait_obj);
}

/// Return the currently registered [`AsyncExecutor`], or `None` if no
/// executor has been installed via [`set_async_executor`]. The returned
/// reference is `&'static` because the registered `Box<dyn AsyncExecutor>`
/// is held inside a `OnceLock` for the program's lifetime.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::current_async_executor;
///
/// // Initially no executor has been installed.
/// assert!(current_async_executor().is_none());
/// ```
pub fn current_async_executor() -> Option<&'static dyn AsyncExecutor> {
    ASYNC_EXECUTOR
        .get()
        .map(|b| b.as_ref() as &'static dyn AsyncExecutor)
}

/// T-003 per-call override probe. Returns an executor that should be
/// preferred over the global slot. The macro's sync-from-async wrapper
/// calls this first; only on `None` does it fall back to
/// [`current_async_executor`] and the active Tokio runtime.
///
/// This hook lets users wire a runtime-aware executor (async-std / smol
/// / embassy) without leaking a global side effect from
/// [`set_async_executor`]. The default implementation returns `None` so
/// existing executors keep their old behaviour.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::block_on_for_executor;
///
/// // Without a registered executor this returns `None`.
/// assert!(block_on_for_executor().is_none());
/// ```
pub fn block_on_for_executor() -> Option<&'static dyn AsyncExecutor> {
    ASYNC_EXECUTOR.get().and_then(|b| b.block_on_for())
}

/// Try to drive `future` to completion using the registered executor, the
/// current Tokio runtime (when available), or a clear English error.
///
/// This is the entry point used by the `#[tool]` macro. It is intentionally
/// panic-free and always returns a [`ToolError`] on failure so the macro
/// can propagate the error through `call_tool_sync` without `unwrap`.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::{block_on_async, set_async_executor, AsyncExecutor, AsyncExecutorExt};
/// use core::future::Future;
/// use core::pin::Pin;
/// use core::any::Any;
///
/// struct InlineExecutor;
/// impl AsyncExecutor for InlineExecutor {
///     fn block_on_dyn(
///         &self,
///         future: Pin<Box<dyn Future<Output = ()> + Send>>,
///     ) -> Box<dyn Any + Send> {
///         futures::executor::block_on(future);
///         Box::new(())
///     }
/// }
///
/// set_async_executor(Box::new(InlineExecutor));
/// let value: i32 = block_on_async(async { 21 + 21 }).unwrap();
/// assert_eq!(value, 42);
/// ```
///
/// # Errors
///
/// Returns a [`ToolError`] of kind [`ToolErrorKind::InternalError`] when no
/// executor is registered and no Tokio runtime is in scope. The `#[tool]`
/// macro also probes for a Tokio runtime and surfaces a richer message via
/// [`block_on_async_error_message`].
#[cfg(feature = "serde")]
pub fn block_on_async<F>(future: F) -> Result<F::Output, ToolError>
where
    F: core::future::Future + Send + 'static,
    F::Output: Send + 'static,
{
    // T-003: probe the per-call override seam *before* the global slot
    // so async-std / smol / embassy users who override `block_on_for`
    // on their registered executor get the per-thread handle when it
    // is reachable.
    if let Some(exec) = block_on_for_executor() {
        return Ok(exec.block_on(future));
    }
    if let Some(exec) = current_async_executor() {
        return Ok(exec.block_on(future));
    }

    // No executor was registered. The `#[tool]` macro's sync wrappers
    // additionally probe the current Tokio runtime as a final fallback;
    // here we only handle the user-registered executor path and return
    // a clear error so the macro can surface a helpful message.
    drop(future);
    Err(ToolError::internal_error(block_on_async_error_message()))
}

/// `no_std`/`no-serde` companion to [`block_on_async`]. Always returns an
/// error because no executor is reachable in a `no_std` build.
///
/// # Errors
///
/// Always returns `Err` with a static explanation string instructing the
/// caller to enable the `serde` feature and register an executor.
#[cfg(not(feature = "serde"))]
pub fn block_on_async<F>(_future: F) -> Result<F, &'static str> {
    Err(
        "no async runtime available in no_std build; enable the `serde` feature \
         and call `tokitai_core::set_async_executor(...)` to enable sync-from-async",
    )
}

/// Canonical English error message returned by the `#[tool]` macro when
/// it cannot find any executor to drive a sync-from-async call. The macro
/// embeds the return value of this function as the error string, so the
/// message is centralised here for consistency and future i18n.
///
/// # Example
///
/// ```rust
/// use tokitai_core::block_on_async_error_message;
///
/// let msg = block_on_async_error_message();
/// assert!(msg.contains("no async runtime"));
/// ```
pub const fn block_on_async_error_message() -> &'static str {
    "no async runtime registered; either call from within an async context, \
     run inside a tokio runtime, or call `tokitai_core::set_async_executor(...)` \
     before invoking"
}

// -------------------------------------------------------------------------
// T-004: runtime-agnostic async sleep.
//
// Resilience decorators (`#[retry]`, `#[rate_limit]`,
// `#[circuit_breaker]`) on `async fn` need to wait between attempts
// without blocking the runtime worker thread. With Tokio that is
// `tokio::time::sleep`; with async-std, `async_std::task::sleep`; with
// smol, `smol::Timer::after`. None of those crates are in scope for
// `tokitai-core` (it is zero-dep / no-`tokio`).
//
// The helper below provides a runtime-agnostic equivalent: spawn a
// thread that parks for the requested duration and wakes the future's
// `Waker` when the deadline elapses. The user-registered executor
// drives the future through `block_on`; the spawned thread is the
// "timer" replacement. This costs one short-lived thread per sleep,
// which is the same trade-off `async-std` / `smol` make internally.
//
// The sleep does NOT pull in any runtime crate — it only uses
// `std::thread` and `std::time`. The future is `Send + 'static` so it
// can cross the `AsyncExecutor` type-erasure boundary, and it is
// `Unpin` so it composes inside `select!`-style macros without an
// unsafe `Pin::get_unsafe_mut`.
// -------------------------------------------------------------------------

/// Runtime-agnostic async sleep future returned by [`async_sleep`].
///
/// Polling the future for the first time spawns a single thread that
/// parks for the requested duration and wakes the registered
/// `Waker` when the deadline elapses. Subsequent polls return
/// `Poll::Pending` until the waker is invoked, at which point the
/// next poll returns `Poll::Ready(())`.
///
/// Used by the resilience decorator macros (`#[retry]`,
/// `#[rate_limit]`, `#[circuit_breaker]`) when wrapped around an
/// `async fn`. The sleep yields to the runtime for the full
/// duration, never blocks the executor thread.
#[cfg(feature = "serde")]
pub struct AsyncSleep {
    /// Deadline measured against `Instant::now()` at construction time.
    deadline: std::time::Instant,
    /// `true` once the timer thread has been spawned.
    armed: bool,
}

#[cfg(feature = "serde")]
impl AsyncSleep {
    /// Construct a sleep that completes after `dur` from "now". The
    /// caller drives the future to completion via whatever executor
    /// it has in scope (Tokio / async-std / smol / custom).
    #[must_use]
    pub fn new(dur: std::time::Duration) -> Self {
        Self {
            deadline: std::time::Instant::now() + dur,
            armed: false,
        }
    }

    /// Time remaining until the deadline elapses. Returns `Duration::ZERO`
    /// once the deadline has passed.
    pub fn remaining(&self) -> std::time::Duration {
        self.deadline
            .saturating_duration_since(std::time::Instant::now())
    }
}

#[cfg(feature = "serde")]
impl core::future::Future for AsyncSleep {
    type Output = ();
    fn poll(
        mut self: core::pin::Pin<&mut Self>,
        cx: &mut core::task::Context<'_>,
    ) -> core::task::Poll<()> {
        // If the deadline has already passed, complete immediately.
        if std::time::Instant::now() >= self.deadline {
            return core::task::Poll::Ready(());
        }
        let remaining = self.remaining();
        if !self.armed {
            // Arm the timer exactly once. The spawned thread parks
            // for `remaining` and then wakes the future's waker.
            // We `clone` the waker so the timer thread can outlive
            // the current `Context` and the future still observes
            // the wake even if it was re-polled in between.
            let waker = cx.waker().clone();
            std::thread::spawn(move || {
                std::thread::park_timeout(remaining);
                waker.wake();
            });
            self.armed = true;
        }
        core::task::Poll::Pending
    }
}

/// Sleep for `dur` without blocking the current thread.
///
/// Returns a future that completes after the given duration. The
/// future is `Send + 'static` and `Unpin`, so it composes with
/// any executor and with `select!`-style combinators.
///
/// This is the **async** counterpart to `std::thread::sleep`:
/// polling the future yields control to the runtime, which is
/// free to drive other tasks while the deadline elapses. The
/// `#[retry]`, `#[rate_limit]`, and `#[circuit_breaker]` macros
/// emit `await tokitai_core::async_sleep(...)` on `async fn`
/// bodies so that backoff between attempts does not stall a
/// runtime worker thread.
///
/// # Example
///
/// ```rust,ignore
/// use tokitai_core::async_sleep;
/// use std::time::Duration;
///
/// async fn retryable() -> Result<(), &'static str> {
///     for attempt in 1..3 {
///         match try_once().await {
///             Ok(()) => return Ok(()),
///             Err(_) if attempt < 3 => {
///                 async_sleep(Duration::from_millis(100 * attempt)).await;
///             }
///             Err(e) => return Err(e),
///         }
///     }
///     Ok(())
/// }
///
/// async fn try_once() -> Result<(), &'static str> { Ok(()) }
/// ```
#[cfg(feature = "serde")]
#[must_use]
pub fn async_sleep(dur: std::time::Duration) -> AsyncSleep {
    AsyncSleep::new(dur)
}

